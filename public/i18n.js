  let currentLang = localStorage.getItem('makruk_lang') === 'en' ? 'en' : 'th';

  function t(key) {
    return TRANSLATIONS[currentLang]?.[key] ?? TRANSLATIONS.th[key] ?? key;
  }

  function getLang() { return currentLang; }

  function setLang(lang) {
    if (lang !== 'th' && lang !== 'en') return;
    currentLang = lang;
    localStorage.setItem('makruk_lang', lang);
    document.documentElement.lang = lang;
    applyTranslations();
    document.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
  }

  function toggleLang() { setLang(currentLang === 'th' ? 'en' : 'th'); }

  function applyTranslations() {
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.getAttribute('data-i18n');
      el.textContent = t(key);
    });
    document.querySelectorAll('[data-i18n-html]').forEach((el) => {
      const key = el.getAttribute('data-i18n-html');
      el.innerHTML = t(key);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      const key = el.getAttribute('data-i18n-placeholder');
      el.placeholder = t(key);
    });
    document.querySelectorAll('[data-i18n-title]').forEach((el) => {
      const key = el.getAttribute('data-i18n-title');
      el.title = t(key);
    });
    const btn = document.getElementById('langToggleBtn');
    if (btn) btn.textContent = currentLang === 'th' ? 'EN' : 'TH';
  }

  document.addEventListener('DOMContentLoaded', () => {
    document.documentElement.lang = currentLang;
    applyTranslations();
  });

  global.I18N = { t, setLang, getLang, toggleLang, applyTranslations };
